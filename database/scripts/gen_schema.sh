#!/usr/bin/env bash
# Regenerate database/schema.sql (readable mirror of the migrations) without needing a database.
# Run from anywhere. After a real DB is available you may instead use: pg_dump --schema-only --no-owner.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- Employee Connect schema (GENERATED by scripts/gen_schema.sh from alembic migrations; migrations are authoritative)."
  echo "-- Do not edit by hand. Includes alembic_version bookkeeping; load with psql as the owner role."
  python -m alembic -c alembic.ini upgrade head --sql 2>/dev/null
} > schema.sql
echo "schema.sql regenerated"
